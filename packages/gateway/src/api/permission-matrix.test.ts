// T1: the permission model matches the code (docs/design/m4-permission-model-2026-10-07.md).
// Every route on both listeners has a stated rule, every stated rule names a real route, and the
// generated route tables in docs/generated/permission-matrix.md are exactly what the code says.
// After a route-policy change, regenerate that file from the repository root with
// `UPDATE_GENERATED=1 npx vitest run packages/gateway/src/api/permission-matrix.test.ts`.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import Fastify from "fastify";
import { afterEach, describe, expect, it } from "vitest";
import { buildGateway } from "../index.js";
import { FakeProvider } from "../test-support/fake-provider.js";
import { testConfig } from "../test-support/harness.js";
import {
  OPERATOR_ROUTE_RULES,
  SANDBOX_ROUTE_RULES,
  permissionMatrixMarkdown,
} from "./permission-matrix.js";
import { ROUTE_POLICY } from "./route-policy.js";
import { registerOperatorRoutes, registerSandboxRoutes } from "./routes.js";

const GENERATED = new URL("../../../../docs/generated/permission-matrix.md", import.meta.url);
const REGENERATE =
  "UPDATE_GENERATED=1 npx vitest run packages/gateway/src/api/permission-matrix.test.ts";

function generatedFile(): string {
  return [
    "# Permission matrix: generated route tables",
    "",
    "<!-- Generated by packages/gateway/src/api/permission-matrix.test.ts; do not edit. -->",
    "",
    "Generated from the code; do not edit by hand. These are the route tables of the",
    "[M4 permission model](../design/m4-permission-model-2026-10-07.md) (section 7): `/api` routes",
    "come from `ROUTE_POLICY` (`packages/gateway/src/api/route-policy.ts`), every other route from",
    "`packages/gateway/src/api/permission-matrix.ts`. After changing either, regenerate this file",
    "from the repository root with:",
    "",
    "```",
    REGENERATE,
    "```",
    "",
    permissionMatrixMarkdown(),
  ].join("\n");
}

const apps: Array<{ close(): Promise<unknown> }> = [];
afterEach(async () => {
  for (const app of apps.splice(0)) await app.close();
});

async function listenerRoutes(): Promise<{ operator: string[]; sandbox: string[] }> {
  const gateway = buildGateway(testConfig(), new FakeProvider(), { startCron: false });
  apps.push(gateway);
  await gateway.ready();
  const { ctx, scheduler, lifecycle } = gateway.deskmates;
  const collect = async (register: (app: ReturnType<typeof Fastify>) => void) => {
    const app = Fastify();
    apps.push(app);
    const routes: string[] = [];
    app.addHook("onRoute", (route) => {
      for (const method of [route.method].flat())
        if (method !== "HEAD") routes.push(`${method} ${route.url}`);
    });
    register(app);
    await app.ready();
    return routes;
  };
  return {
    operator: await collect((app) => registerOperatorRoutes(app, ctx, scheduler)),
    sandbox: await collect((app) => registerSandboxRoutes(app, ctx, lifecycle, scheduler)),
  };
}

describe("permission model", () => {
  it("states a rule for every route on both listeners, and only for real routes", async () => {
    const { operator, sandbox } = await listenerRoutes();
    const outsideGuard = operator.filter((route) => !(route in ROUTE_POLICY));
    expect(outsideGuard.sort()).toEqual(Object.keys(OPERATOR_ROUTE_RULES).sort());
    expect(sandbox.sort()).toEqual(Object.keys(SANDBOX_ROUTE_RULES).sort());
  });

  it("publishes exactly the generated route tables", () => {
    const generated = generatedFile();
    if (process.env.UPDATE_GENERATED === "1") {
      mkdirSync(new URL(".", GENERATED), { recursive: true });
      writeFileSync(GENERATED, generated);
      return;
    }
    const published = existsSync(GENERATED) ? readFileSync(GENERATED, "utf8") : "";
    expect(
      published,
      `docs/generated/permission-matrix.md is out of date; regenerate it with \`${REGENERATE}\``,
    ).toBe(generated);
  });
});
