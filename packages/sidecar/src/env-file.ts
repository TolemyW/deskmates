// `/run/deskmates/env`: KEY=VALUE lines injected by the sandbox provider (ADR-0002 decision 4).
// Only the model base URL and the short-lived token are expected there; nothing is interpreted.

export const RUNTIME_ENV_FILE = "/run/deskmates/env";

/** Parse KEY=VALUE lines. Blank lines and `#` comments are ignored; matching quotes are stripped. */
export function parseEnvFile(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line === "" || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1);
    }
    if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) out[key] = value;
  }
  return out;
}
