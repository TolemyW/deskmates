// Everything this package writes, as repository-relative paths and their content. The only writer
// is `generated.test.ts` with UPDATE_GENERATED=1; without it that test fails when a committed
// file differs, so the files under observability/grafana/ are never edited by hand.

import { DASHBOARDS } from "./dashboards/index.js";
import { ENGINES, dashboardProviderYaml } from "./engines.js";
import { grafanaDashboard } from "./grafana.js";

export interface GeneratedFile {
  /** Relative to the repository root. */
  path: string;
  content: string;
}

export const OUTPUT_ROOT = "observability/grafana";

export const REFRESH_COMMAND =
  "UPDATE_GENERATED=1 npx vitest run packages/observability-dashboards/src/generated.test.ts";

function readme(): string {
  const engines = ENGINES.map((engine) => `\`${engine.id}\``).join(", ");
  const dashboards = DASHBOARDS.map((d) => `- \`${d.slug}.json\`: ${d.title}`);
  return [
    "# Grafana provisioning (generated)",
    "",
    "<!-- Generated by packages/observability-dashboards/src/generated.test.ts; do not edit. -->",
    "",
    "Written by `packages/observability-dashboards` from one panel spec (ADR-0046 decision 7) and",
    "committed; `scripts/stable/stable.sh grafana start` mounts the active release's copy into",
    "Grafana. Do not edit these files: change the spec and regenerate from the repository root with",
    "",
    "```",
    REFRESH_COMMAND,
    "```",
    "",
    `One directory per engine (${engines}), each holding:`,
    "",
    "- `provisioning/datasources/deskmates.yaml`: the obs datasource, read-only.",
    "- `provisioning/dashboards/deskmates.yaml`: the file provider for `dashboards/`.",
    "- `dashboards/`:",
    ...dashboards.map((line) => `  ${line}`),
    "",
  ].join("\n");
}

export function generatedFiles(): GeneratedFile[] {
  const files: GeneratedFile[] = [{ path: `${OUTPUT_ROOT}/README.md`, content: readme() }];
  for (const engine of ENGINES) {
    const dir = `${OUTPUT_ROOT}/${engine.id}`;
    files.push(
      { path: `${dir}/provisioning/datasources/deskmates.yaml`, content: engine.datasourceYaml() },
      { path: `${dir}/provisioning/dashboards/deskmates.yaml`, content: dashboardProviderYaml() },
    );
    for (const spec of DASHBOARDS)
      files.push({
        path: `${dir}/dashboards/${spec.slug}.json`,
        content: `${JSON.stringify(grafanaDashboard(spec, engine), null, 2)}\n`,
      });
  }
  return files.sort((a, b) => a.path.localeCompare(b.path));
}
