// What differs per engine besides the SQL dialect: the Grafana datasource plugin, how a panel's
// query is put in a Grafana target, and the provisioning files Grafana reads at start. The paths
// inside the container are the contract with `scripts/stable/stable.sh grafana start`, which
// mounts the release's `observability/grafana/<engine>/` directories there.

import { type Dialect, sqliteDialect } from "./dialect.js";
import type { PanelKind } from "./spec.js";

/** Where `stable.sh` mounts the directory holding the obs file, read-only. */
export const OBS_DIR_IN_CONTAINER = "/var/lib/deskmates-obs";

/** Where `stable.sh` mounts the engine's `dashboards/` directory, read-only. */
export const DASHBOARDS_DIR_IN_CONTAINER = "/var/lib/deskmates-dashboards";

/** The Grafana datasource every generated panel names. */
export const DATASOURCE_UID = "deskmates-obs";

export interface Engine {
  id: string;
  dialect: Dialect;
  /** The Grafana datasource plugin id. */
  datasourceType: string;
  /** A Grafana query target for one panel query. */
  target(sql: string, kind: PanelKind): Record<string, unknown>;
  /** `provisioning/datasources/deskmates.yaml`. */
  datasourceYaml(): string;
}

const GENERATED_YAML =
  "# Generated by packages/observability-dashboards (src/generated.test.ts); do not edit.\n" +
  "# Refresh: UPDATE_GENERATED=1 npx vitest run packages/observability-dashboards/src/generated.test.ts\n";

/**
 * The built-in engine: `obs.sqlite` through the SQLite datasource plugin that `images/grafana`
 * preinstalls. The file is opened read-only (`mode=ro`); the directory is mounted rather than the
 * file because a WAL reader needs the `-wal` and `-shm` files beside it. `DESKMATES_OBS_FILE` is
 * the file's name, which `stable.sh` passes as an environment variable and Grafana substitutes.
 */
export const sqliteEngine: Engine = {
  id: "sqlite",
  dialect: sqliteDialect,
  datasourceType: "frser-sqlite-datasource",
  target: (sql, kind) => ({
    queryType: kind === "timeseries" ? "time series" : "table",
    rawQueryText: sql,
    queryText: sql,
    timeColumns: ["time"],
  }),
  datasourceYaml: () =>
    [
      GENERATED_YAML,
      "apiVersion: 1",
      "datasources:",
      "  - name: Deskmates observability",
      `    uid: ${DATASOURCE_UID}`,
      "    type: frser-sqlite-datasource",
      "    access: proxy",
      "    isDefault: true",
      "    editable: false",
      "    jsonData:",
      `      path: ${OBS_DIR_IN_CONTAINER}/\${DESKMATES_OBS_FILE}`,
      '      pathPrefix: "file:"',
      '      pathOptions: "?mode=ro"',
      "",
    ].join("\n"),
};

/** The dashboard provider: one folder, files only, no edits from the UI. Same for every engine. */
export function dashboardProviderYaml(): string {
  return [
    GENERATED_YAML,
    "apiVersion: 1",
    "providers:",
    "  - name: deskmates",
    "    orgId: 1",
    "    folder: Deskmates",
    "    type: file",
    "    disableDeletion: true",
    "    allowUiUpdates: false",
    "    updateIntervalSeconds: 60",
    "    options:",
    `      path: ${DASHBOARDS_DIR_IN_CONTAINER}`,
    "",
  ].join("\n");
}

/** Every engine the generator writes, sorted by id. */
export const ENGINES: readonly Engine[] = [sqliteEngine];
